<?php

namespace App\Models;

use App\Support\Quran;
use Database\Factories\AyahFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;

#[Fillable(['id', 'surah_number', 'surah_name', 'ayah_number', 'text_uthmani'])]
class Ayah extends Model
{
    /** @use HasFactory<AyahFactory> */
    use HasFactory;

    /**
     * Identifiers are deterministic (surah * 1000 + ayah), so they are never
     * generated by the database.
     */
    public $incrementing = false;

    /**
     * @var string
     */
    protected $keyType = 'int';

    /**
     * Keep the composite identifier and the surah name in sync with the
     * surah/ayah coordinate whenever a verse is created or edited by hand.
     */
    protected static function booted(): void
    {
        static::saving(function (Ayah $ayah): void {
            $surah = (int) $ayah->surah_number;
            $ayahNumber = (int) $ayah->ayah_number;

            if ($surah > 0 && $ayahNumber > 0) {
                $ayah->id = self::composeId($surah, $ayahNumber);
            }

            $ayah->surah_name = self::normalizeSurahName((string) $ayah->surah_name, $surah);
            $ayah->text_uthmani = self::normalizeText((string) $ayah->text_uthmani);
        });

        // Every stored verse has a correct and a wrong recitation task. The
        // bulk importer writes with upsert (no model events) and refreshes the
        // pool explicitly, while manual admin edits are synchronised here.
        static::saved(function (Ayah $ayah): void {
            if ($ayah->wasRecentlyCreated || $ayah->wasChanged(['text_uthmani', 'surah_number', 'ayah_number'])) {
                RecitationTask::syncForAyah($ayah);
            }
        });
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'surah_number' => 'integer',
            'ayah_number' => 'integer',
        ];
    }

    /**
     * @return HasMany<Recording, $this>
     */
    public function recordings(): HasMany
    {
        return $this->hasMany(Recording::class);
    }

    /**
     * Student reports flagging the text of this ayah.
     *
     * @return HasMany<AyahReport, $this>
     */
    public function reports(): HasMany
    {
        return $this->hasMany(AyahReport::class);
    }

    /**
     * Composite mushaf identifier, e.g. surah 2 / ayah 255 => 2255.
     */
    public static function composeId(int $surahNumber, int $ayahNumber): int
    {
        return Quran::ayahId($surahNumber, $ayahNumber);
    }

    /**
     * Six digit display identifier, e.g. 1003 => "001003".
     */
    public function getCodeAttribute(): string
    {
        return Quran::formatAyahId($this->id);
    }

    /**
     * Localised reference such as "سورة الفاتحة · الآية 2".
     */
    public function getReferenceAttribute(): string
    {
        return sprintf('%s · الآية %d', $this->surah_name, $this->ayah_number);
    }

    /**
     * Collapse whitespace (including newlines and non-breaking spaces) so the
     * imported text is stored exactly as one readable line.
     */
    public static function normalizeText(string $text): string
    {
        $text = preg_replace('/[\s\x{00A0}\x{200B}\x{FEFF}]+/u', ' ', $text) ?? $text;

        return trim($text);
    }

    /**
     * Store the surah name in the canonical "سورة ..." form used by the dataset.
     */
    public static function normalizeSurahName(string $name, int $surahNumber): string
    {
        $name = trim($name);

        if ($name === '') {
            return Quran::surahFullName($surahNumber);
        }

        return str_starts_with($name, 'سورة') ? $name : 'سورة '.$name;
    }

    /**
     * @param  Builder<Ayah>  $query
     * @return Builder<Ayah>
     */
    public function scopeForSurah(Builder $query, int|string|null $surah): Builder
    {
        if ($surah === null || $surah === '' || $surah === 'all') {
            return $query;
        }

        return $query->where('surah_number', (int) $surah);
    }

    /**
     * Mushaf order. The identifier already encodes surah/ayah ordering.
     *
     * @param  Builder<Ayah>  $query
     * @return Builder<Ayah>
     */
    public function scopeOrdered(Builder $query): Builder
    {
        return $query->orderBy('surah_number')->orderBy('ayah_number')->orderBy('id');
    }
}
